#!/bin/sh
# Activate the secret guard (.pre-commit-config.yaml) in this clone. Run it from the
# default branch's reviewed copy, never from a checkout:
#
#   pipx install pre-commit==4.7.0
#   git show origin/HEAD:.secret-guard/activate.sh | sh
#
# Re-run it after .pre-commit-config.yaml or this script changes on the default branch.
#
# Why not `pre-commit install`: its hook reads the checked-out .pre-commit-config.yaml, and
# gitleaks reads a checked-out .gitleaks.toml, so checking out a fork PR and committing
# would run whatever hooks and scanning policy that branch defines. The hook written here
# reads copies kept in the git directory instead.
set -eu

ref=${SECRET_GUARD_REF:-origin/HEAD}
command -v pre-commit >/dev/null 2>&1 || {
  echo "secret guard: pre-commit not found; pipx install pre-commit==4.7.0" >&2; exit 1; }

d=$(git rev-parse --path-format=absolute --git-common-dir)
git show "$ref:.pre-commit-config.yaml" > "$d/secret-guard.yaml"
# Gitleaks' built-in rules. GITLEAKS_CONFIG outranks a .gitleaks.toml in the checkout.
printf '[extend]\nuseDefault = true\n' > "$d/secret-guard-gitleaks.toml"

run="GITLEAKS_CONFIG=\"$d/secret-guard-gitleaks.toml\" pre-commit run --config \"$d/secret-guard.yaml\" --hook-stage pre-commit"

hooks_path=$(git config core.hooksPath || true)
if [ -n "$hooks_path" ]; then
  if grep -qs 'secret-guard.yaml' "$hooks_path/pre-commit"; then
    echo "secret guard: copies refreshed from $ref; $hooks_path/pre-commit runs them"; exit 0
  fi
  echo "secret guard: core.hooksPath is $hooks_path, so a hook in $d/hooks would never run." >&2
  echo "Make $hooks_path/pre-commit run:  $run" >&2
  exit 1
fi

hook="$d/hooks/pre-commit"
mkdir -p "$d/hooks"
if [ -e "$hook" ] && ! grep -q 'secret-guard.yaml' "$hook"; then
  if grep -q 'File generated by pre-commit' "$hook"; then
    rm -f "$hook"   # pre-commit's own hook reads the checkout; the guard replaces it
  else
    mv "$hook" "$hook.legacy"
    echo "secret guard: kept the existing hook as $hook.legacy; it runs after the guard"
  fi
fi

cat > "$hook" <<EOF
#!/bin/sh
# Secret guard, written by .secret-guard/activate.sh. Reads reviewed copies in the git
# directory, not the checkout.
$run || exit 1
if [ -x "$hook.legacy" ]; then exec "$hook.legacy" "\$@"; fi
EOF
chmod +x "$hook"
echo "secret guard active (config from $ref: $d/secret-guard.yaml)"
